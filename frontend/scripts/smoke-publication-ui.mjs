import assert from "node:assert/strict";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1500, height: 1100 } });
  const errors = []; const mutations = [];
  page.on("pageerror", e => errors.push(e.message));
  page.on("request", r => { if (r.method() === "POST") mutations.push(r.url()); });
  await page.goto("http://localhost:5173/annotation?tab=publish");
  await page.getByRole("heading", { name: "待发布区", exact: true }).waitFor();
  await page.locator(".pub-sample").first().waitFor();
  const count = await page.locator(".pub-sample").count();
  assert.ok(count > 0 && count <= 12);
  await page.getByRole("button", { name: "全选", exact: true }).click();
  await page.getByRole("status").filter({ hasText: "已全选当前来源" }).waitFor();
  assert.equal(await page.locator(".pub-sample input:checked").count(), count);
  await page.getByRole("button", { name: "清空", exact: true }).click();
  assert.equal(await page.locator(".pub-sample input:checked").count(), 0);
  await page.getByRole("button", { name: "选择本页", exact: true }).click();
  await page.getByRole("textbox", { name: "发布数据集名称" }).fill("UI 验收（不发布）");
  assert.ok(await page.getByRole("button", { name: "检查发布清单", exact: true }).isEnabled());
  await page.getByRole("spinbutton", { name: "训练集 %", exact: true }).fill("90");
  assert.ok(await page.getByRole("button", { name: "检查发布清单", exact: true }).isDisabled());
  await page.getByRole("spinbutton", { name: "训练集 %", exact: true }).fill("80");
  await page.screenshot({ path: "/tmp/finevision-publication-desktop.png", fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.setViewportSize({ width: 390, height: 1000 });
  await page.screenshot({ path: "/tmp/finevision-publication-mobile.png", fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.getByRole("button", { name: "追加已有数据集", exact: true }).click();
  assert.equal(await page.locator(".pub-mapping").count(), 0);
  await page.getByText("保留已确认类别名称。同名类别自动追加，不存在的类别加入新版本，无需重新指定标签。", { exact: true }).waitFor();
  await page.getByRole("button", { name: "推理回流", exact: true }).click();
  assert.ok(await page.getByRole("button", { name: "新建数据集", exact: true }).isDisabled());
  await page.getByText("新样本 100% 加入训练集。历史验证集、测试集保持不变。", { exact: true }).waitFor();
  await page.getByRole("button", { name: "发布记录", exact: true }).click();
  await page.getByRole("heading", { name: "发布记录", exact: true }).waitFor();
  assert.deepEqual(errors, []); assert.deepEqual(mutations, []);
  console.log("Publication UI passed: selection, ratio validation, feedback train-only guard, tabs, desktop/mobile overflow; no mutations.");
} finally { await browser.close(); }
