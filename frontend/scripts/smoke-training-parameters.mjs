import assert from "node:assert/strict";
import { trainingHeadConfig, trainingParameterRows, resolutions } from "../src/features/training/trainingParameters.js";
import { normalizeTrainingRun } from "../src/api/trainingRuns.js";
const form = { backboneKey: "dinov3_vits16_lvd1689m", epochs: "30", batchSize: "8", loraEnabled: false, loraRank: "8", headLearningRate: "1e-3", backboneLearningRate: "1e-5", loraLearningRate: "2e-4", augmentations: { horizontal_flip: true } };
let config = trainingHeadConfig(form);
assert.equal(config.head_learning_rate, .001);
assert.equal(config.backbone_learning_rate, undefined);
assert.equal(config.lora_learning_rate, undefined);
config = trainingHeadConfig({ ...form, loraEnabled: true });
assert.equal(config.lora_learning_rate, .0002);
config = trainingHeadConfig({ ...form, backboneKey: "imagenet_vits16_augreg_in21k_ft_in1k", loraEnabled: true });
assert.equal(config.lora_enabled, false);
assert.equal(config.lora_learning_rate, undefined);
assert.equal(config.backbone_learning_rate, .00001);
const run = normalizeTrainingRun({ head_config: config, backbone_id: "imagenet_vits16_augreg_in21k_ft_in1k", extractor_config: { image_size: 320 } });
const rows = Object.fromEntries(trainingParameterRows(run));
assert.equal(rows["输入分辨率"], "320 × 320");
assert.equal(rows["骨干学习率"], .00001);
assert.equal(rows["训练集增强"], "水平翻转");
assert.ok(resolutions.every(n => n % 16 === 0));
console.log("Training parameter payload, mode isolation and detail display passed");
