import assert from "node:assert/strict";
import { paginateItems as paginateDatasets, pageNumbers as datasetPageNumbers } from "../src/design-system/components/pagination.js";
const items = Array.from({ length: 12 }, (_, id) => ({ id }));
const first = paginateDatasets(items, 1, 5);
assert.equal(first.pageCount, 3);
assert.deepEqual(first.items.map(x => x.id), [0, 1, 2, 3, 4]);
assert.deepEqual(paginateDatasets(items, 2, 5).items.map(x => x.id), [5, 6, 7, 8, 9]);
const last = paginateDatasets(items, 3, 5);
assert.deepEqual(last.items.map(x => x.id), [10, 11]);
assert.equal(last.start, 11); assert.equal(last.end, 12);
assert.equal(paginateDatasets(items.slice(0, 2), 3, 5).page, 1);
assert.equal(paginateDatasets(items, 1, 10).items.length, 10);
const empty = paginateDatasets([], 3, 5);
assert.equal(empty.page, 1); assert.equal(empty.pageCount, 1);
assert.equal(empty.start, 0); assert.equal(empty.end, 0);
assert.deepEqual(empty.items, []);
assert.equal(items.length, 12);
assert.equal(paginateDatasets(items, 1, 6).items.length, 6);
assert.deepEqual(paginateDatasets(items, 2, 6).items.map(x => x.id), [6, 7, 8, 9, 10, 11]);
console.log("dataset pagination smoke passed");
assert.deepEqual(datasetPageNumbers(2, 3), [1, 2, 3]);
assert.deepEqual(datasetPageNumbers(5, 10), [1, null, 4, 5, 6, null, 10]);
assert.deepEqual(datasetPageNumbers(1, 1), [1]);
